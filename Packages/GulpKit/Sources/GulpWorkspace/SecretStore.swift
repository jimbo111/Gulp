// GulpWorkspace — where secrets live instead of the project file (CLAUDE.md "No secrets in the
// repo"). A `.gulp` project is a file people share, attach to tickets and commit; signing keys and
// cloud credentials must not travel with it. The project stores a reference; the material goes here:
// the macOS Keychain for the app, a directory of mode-0600 files elsewhere (Linux, CLI, tests) — the
// same split as the CA key (`CAStore`).

import Foundation

#if canImport(Security)
import Security
#endif

/// Secret material by name, outside the project file.
public protocol SecretStore: Sendable {
    /// The secret stored under `name`, or nil if there is none.
    func read(_ name: String) throws -> Data?
    /// Store `data` under `name`, replacing any previous value.
    func write(_ data: Data, name: String) throws
    /// Remove the secret under `name` (no error if it is absent).
    func delete(_ name: String) throws
}

/// A secret store failure.
public struct SecretStoreError: Error, Sendable, CustomStringConvertible {
    /// What went wrong.
    public let description: String
}

/// Secrets as files in one private directory (0700), each file mode 0600.
public struct FileSecretStore: SecretStore {
    /// The directory holding the secret files.
    public let directory: URL

    /// A store in `directory` (created on first write).
    public init(directory: URL) {
        self.directory = directory
    }

    /// The secret stored under `name`, or nil if there is none.
    public func read(_ name: String) throws -> Data? {
        let url = try fileURL(name)
        guard FileManager.default.fileExists(atPath: url.path) else { return nil }
        return try Data(contentsOf: url)
    }

    /// Store `data` under `name` (mode 0600; never briefly world-readable).
    public func write(_ data: Data, name: String) throws {
        let manager = FileManager.default
        try manager.createDirectory(
            at: directory, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
        let url = try fileURL(name)
        if manager.fileExists(atPath: url.path) { try manager.removeItem(at: url) }
        guard manager.createFile(atPath: url.path, contents: data, attributes: [.posixPermissions: 0o600])
        else {
            throw SecretStoreError(description: "cannot write \(url.path)")
        }
    }

    /// Remove the secret under `name`.
    public func delete(_ name: String) throws {
        let url = try fileURL(name)
        if FileManager.default.fileExists(atPath: url.path) { try FileManager.default.removeItem(at: url) }
    }

    /// Names are generated by Gulp, but never let one escape the directory.
    func fileURL(_ name: String) throws -> URL {
        let allowed = CharacterSet.alphanumerics.union(CharacterSet(charactersIn: "-_."))
        guard !name.isEmpty, !name.hasPrefix("."), name.unicodeScalars.allSatisfy(allowed.contains) else {
            throw SecretStoreError(description: "invalid secret name '\(name)'")
        }
        return directory.appendingPathComponent(name)
    }
}

#if canImport(Security)
/// Secrets as Keychain generic-password items (this device only, readable when unlocked).
public struct KeychainSecretStore: SecretStore {
    /// Keychain service name the items are filed under.
    public let service: String

    /// A store under `service`.
    public init(service: String = "com.gulp.app.secrets") {
        self.service = service
    }

    func query(_ name: String) -> [String: Any] {
        [
            kSecClass as String: kSecClassGenericPassword, kSecAttrService as String: service,
            kSecAttrAccount as String: name,
        ]
    }

    /// The secret stored under `name`, or nil if there is none.
    public func read(_ name: String) throws -> Data? {
        var query = query(name)
        query[kSecReturnData as String] = true
        query[kSecMatchLimit as String] = kSecMatchLimitOne
        var result: CFTypeRef?
        let status = SecItemCopyMatching(query as CFDictionary, &result)
        if status == errSecItemNotFound { return nil }
        guard status == errSecSuccess, let data = result as? Data else {
            throw SecretStoreError(description: "Keychain read failed (\(status))")
        }
        return data
    }

    /// Store `data` under `name`, replacing any previous value.
    public func write(_ data: Data, name: String) throws {
        SecItemDelete(query(name) as CFDictionary)
        var item = query(name)
        item[kSecValueData as String] = data
        item[kSecAttrAccessible as String] = kSecAttrAccessibleWhenUnlockedThisDeviceOnly
        item[kSecAttrLabel as String] = "Gulp signing key (\(name))"
        let status = SecItemAdd(item as CFDictionary, nil)
        guard status == errSecSuccess else {
            throw SecretStoreError(description: "Keychain write failed (\(status))")
        }
    }

    /// Remove the secret under `name`.
    public func delete(_ name: String) throws {
        let status = SecItemDelete(query(name) as CFDictionary)
        guard status == errSecSuccess || status == errSecItemNotFound else {
            throw SecretStoreError(description: "Keychain delete failed (\(status))")
        }
    }
}
#endif
